      <section id="features" class="feature-band" aria-label="Core features">
        <article>
          <h2>Trackpad and keyboard</h2>
          <p>Move, click, scroll, zoom, type, and use common shortcuts from your mobile device. On a sensor-equipped phone or tablet, Enhanced capabilities over HTTPS also add a hold-to-move gyro mouse.</p>
        </article>
        <article>
          <h2>Control from another computer</h2>
          <p>View one selected Windows display and its system sound live, then use any browser with a mouse or trackpad and physical keyboard to click, drag, scroll, and type directly on it. Sound starts muted on every connection.</p>
        </article>
        <article>
          <h2>View PC screen from a touch device</h2>
          <p>View one selected Windows display and its system sound live on a phone or tablet. Sound starts muted and offers High, Standard, and Low quality choices with a PC default and optional setting for each device. Use touch gestures for cursor movement, local zoom and pan, and scrolling, with a separate Click control for precise clicks. Capture a native PNG, or record up to five minutes of the clean PC picture locally with PC sound when Sound is on at the start, then save or share the browser-selected MP4 or WebM file from the device.</p>
        </article>
        <article>
          <h2>Switch between open apps</h2>
          <p>Flick through previews of open PC windows, tap the centered card to restore or focus it, swipe up to close it normally, or open applications defined on the PC.</p>
        </article>
        <article>
          <h2>Use Windows PowerShell remotely</h2>
          <p>Open an interactive Windows PowerShell terminal from a paired phone, tablet, or browser. Run commands over Direct LAN or the encrypted Cloud relay, with touch shortcuts, selectable output, copy, two-axis scrolling, and authenticated reconnect.</p>
        </article>
        <article>
          <h2>Ask the AI Assistant</h2>
          <p>Type or dictate a question to get Voltura Air help, troubleshoot a feature, or investigate information available to your Windows account from a personal paired device. It appears when Codex is installed and signed in on the PC and works over Direct LAN or Cloud relay.</p>
        </article>
        <article>
          <h2>Use your phone as a webcam</h2>
          <p>Use any paired-phone camera as a Windows webcam over Enhanced Direct or Cloud relay. Optional audio is off by default and supports mute and testing. It requires separately installed <a href="https://vb-audio.com/Cable/">VB-CABLE</a>, third-party donationware from VB-Audio that is not included with Voltura Air and is used under its own licence.</p>
        </article>
        <article>
          <h2>Files</h2>
          <p>Browse files on the PC or mapped drives. Use one or two touch panels for file management, save one selected PC file to your device, or upload one chosen device file into the active PC folder.</p>
        </article>
        <article>
          <h2>Cloud relay for restricted networks</h2>
          <p>Connect through restricted company or guest networks without an incoming PC firewall exception. Keep the same QR pairing, trusted devices, and permissions.</p>
        </article>
        <article>
          <h2>Presentation remote</h2>
          <p>Control PowerPoint, Google Slides, and PDF/browser presentations with a laser pointer, timer, and saved reports.</p>
        </article>
        <article>
          <h2>Text and dictation</h2>
          <p>Dictate, reuse snippets, or compose text, then send it to a PC app or clipboard. Supporting HTTPS browsers can paste from this device's clipboard, get PC clipboard text into a visible box, or fetch fresh PC clipboard text directly into the current phone, tablet, or computer's clipboard.</p>
        </article>
        <article>
          <h2>Couch remote</h2>
          <p>Control media, volume, YouTube, Kodi, browser tabs, windows, and approved PC apps.</p>
        </article>
        <article>
          <h2>Custom screens</h2>
          <p>Build responsive control screens with buttons, panels, trackpads, navigation rings, and D-pads. Preview, assign, import, export, or browse reviewed community designs.</p>
        </article>
        <article>
          <h2>PC actions</h2>
          <p>Keep the PC awake, lock it, blank its displays, restart it, or shut it down when allowed.</p>
        </article>
        <article>
          <h2>Tablet split mode</h2>
          <p>Use a landscape tablet as a roomy keyboard and trackpad.</p>
        </article>
      </section>

