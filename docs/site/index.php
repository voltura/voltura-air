      <section id="features" class="feature-band" aria-label="Core features">
        <article>
          <h2>Trackpad and keyboard</h2>
          <p>Move, click, scroll, zoom, type, and use common shortcuts from your mobile device.</p>
        </article>
        <article>
          <h2>Control from another computer</h2>
          <p>View one selected Windows display live, then use any browser with a mouse or trackpad and physical keyboard to click, drag, scroll, and type directly on it.</p>
        </article>
        <article>
          <h2>View PC screen from a touch device</h2>
          <p>View one selected Windows display live on a phone or tablet. Use touch gestures for cursor movement, local zoom and pan, and scrolling, with a separate Click control for precise clicks.</p>
        </article>
        <article>
          <h2>Files on PC</h2>
          <p>Browse files that stay on the PC or mapped drives. Use one or two touch panels for direct copy and move, Windows clipboard actions, properties, Recycle Bin deletion, and background progress.</p>
        </article>
        <article>
          <h2>Cloud relay for restricted networks</h2>
          <p>Connect through restricted company or guest networks without an incoming PC firewall exception. Keep the same QR pairing, trusted devices, and permissions.</p>
        </article>
        <article>
          <h2>Presentation remote</h2>
          <p>Control PowerPoint, Google Slides, and PDF/browser presentations with a laser pointer, timer, and saved reports.</p>
        </article>
        <article>
          <h2>Text and dictation</h2>
          <p>Dictate, reuse snippets, or compose text, then send it to a PC app or clipboard.</p>
        </article>
        <article>
          <h2>Couch remote</h2>
          <p>Control media, volume, YouTube, Kodi, browser tabs, windows, and approved PC apps.</p>
        </article>
        <article>
          <h2>Custom screens</h2>
          <p>Build responsive control screens with buttons, panels, trackpads, navigation rings, and D-pads. Preview, assign, import, export, or browse reviewed community designs.</p>
        </article>
        <article>
          <h2>PC actions</h2>
          <p>Keep the PC awake, lock it, blank its displays, restart it, or shut it down when allowed.</p>
        </article>
        <article>
          <h2>Tablet split mode</h2>
          <p>Use a landscape tablet as a roomy keyboard and trackpad.</p>
        </article>
      </section>

      <section id="work-from-another-pc" class="content-section split">
        <div>
          <p class="eyebrow">View PC screen</p>
          <h2>More than a screen viewer</h2>
        </div>
        <div>
          <p>
            Open Voltura Air in a browser on another computer to view a selected
            Windows display live. Enable direct control to use that computer's
            physical mouse, trackpad, and keyboard to move, left- or right-click,
            drag, scroll, and type on the PC you are viewing.
          </p>
          <p>
            It works over Direct LAN or the encrypted Cloud relay. The Windows
            host chooses the <strong>Screen viewing</strong> and
            <strong>Pointer and keyboard</strong> permissions; direct control
            starts off, one authorized device can view one selected display at a
            time, and browser-reserved shortcuts may remain local.
          </p>
        </div>
      </section>

